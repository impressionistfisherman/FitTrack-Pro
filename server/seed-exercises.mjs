async function seed() {
  const conn = await mysql.createConnection(process.env.DATABASE_URL);
  
  console.log(`Seeding ${exercises.length} exercises...`);
  
  for (const ex of exercises) {
    await conn.execute(
      `INSERT INTO exercises (name, nameKo, bodyPart, equipment, category, difficulty, description, descriptionKo, primaryMuscles, secondaryMuscles, gifUrl, instructions)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
       ON DUPLICATE KEY UPDATE nameKo = VALUES(nameKo)`,
      [
        ex.name,
        ex.nameKo,
        ex.bodyPart,
        ex.equipment,
        ex.category,
        ex.difficulty,
        ex.description,
        ex.descriptionKo,
        JSON.stringify(ex.primaryMuscles),
        JSON.stringify(ex.secondaryMuscles),
        ex.gifUrl,
        JSON.stringify(ex.instructions),
      ]
    );
  }
  
  console.log(`✅ Seeded ${exercises.length} exercises successfully!`);
  await conn.end();
}

